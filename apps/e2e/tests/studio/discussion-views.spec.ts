import { expect, fixture } from '../../support/fixtures'
import { ModelFolder, test } from '../../support/folder'
import type { Page } from '@playwright/test'
import type { Discussions } from '@radical/common/discussions'

let folder: ModelFolder
test.beforeEach(async ({ page, studio }) => {
  folder = new ModelFolder(page)
  await folder.install()
  const data = JSON.parse(fixture('bookstore'))
  data.views.push({ id: 'v-wiki', name: 'Discussion Wiki', kind: 'wiki', nodeIds: [], positions: {} })
  await studio.seedDocument(JSON.stringify(data))
  await studio.open('v-context')
  await expect(studio.nodes).toHaveCount(3)
})

async function moveToFolder(page: Page): Promise<void> {
  await page.getByRole('button', { name: 'Models', exact: true }).click()
  await page.getByRole('menuitem', { name: /Manage models/ }).click()
  await page.getByRole('button', { name: 'Actions for E2E' }).click()
  await page.getByRole('menuitem', { name: 'Move to a folder…' }).click()
  const models = page.getByRole('dialog', { name: 'Models' })
  await expect(models.locator('.docmgr-badge.md')).toBeVisible()
  await models.getByRole('button', { name: 'Close' }).click()
}
async function view(page: Page, name: string): Promise<void> {
  await page.locator('.lp-view-card', { hasText: name }).click()
}
const chooseDiscuss = (page: Page) => page.getByRole('menuitem', { name: 'Discuss', exact: true }).click()

test('table rows and wiki page menus share node threads and preserve drafts across views', async ({ page, studio }) => {
  await moveToFolder(page)
  await view(page, 'Element Table')
  await studio.row('customer').focus()
  await page.keyboard.press('Shift+F10')
  await expect(page.getByRole('menuitem', { name: 'Discuss', exact: true })).toBeFocused()
  await page.keyboard.press('Enter')
  const customer = page.getByRole('dialog', { name: 'Customer', exact: true })
  await customer.getByLabel('Comment (Markdown supported)').fill('Draft started from the table')
  await view(page, 'Discussion Wiki')
  await expect(customer.getByLabel('Comment (Markdown supported)')).toHaveValue('Draft started from the table')
  await customer.getByRole('button', { name: 'Close discussions' }).click()
  await page.locator('.wiki-nav-item[title="Customer"]').click()
  // The body of the page is an entry point as well as its heading.
  await page.locator('.wiki-page').getByText('Buys books online', { exact: true }).click({ button: 'right' })
  await chooseDiscuss(page)
  await expect(customer.getByLabel('Comment (Markdown supported)')).toHaveValue('Draft started from the table')
  await customer.getByRole('button', { name: 'Post comment' }).click()
  await expect(customer.getByRole('status')).toHaveText('Posted.')
  await customer.getByRole('button', { name: 'Close discussions' }).click()
  await expect(page.locator('.wiki-doc[data-wiki-node-id="customer"]')).toBeFocused()
  await page.locator('.wiki-nav-item[title="Bookstore"]').click()
  await page.locator('.wiki-title-row').click({ button: 'right' })
  await chooseDiscuss(page)
  const bookstore = page.getByRole('dialog', { name: 'Bookstore', exact: true })
  await expect(bookstore.locator('.discussion-comment')).toHaveCount(0)
  await bookstore.getByLabel('Comment (Markdown supported)').fill('Bookstore draft')
  await bookstore.getByRole('button', { name: 'Close discussions' }).click()
  // Discussing a navigation entry must not redirect to the current page's node.
  await page.locator('.wiki-nav-item[title="Customer"]').click({ button: 'right' })
  await chooseDiscuss(page)
  await expect(customer.locator('.discussion-comment')).toContainText('Draft started from the table')
  await expect(page.locator('.wiki-title')).toHaveText('Bookstore')
  await customer.getByRole('button', { name: 'Close discussions' }).click()
  await view(page, 'Element Table')
  await studio.row('bookstore').click({ button: 'right' })
  await chooseDiscuss(page)
  await expect(bookstore.getByLabel('Comment (Markdown supported)')).toHaveValue('Bookstore draft')
  await bookstore.getByRole('button', { name: 'Post comment' }).click()
  await expect(bookstore.getByRole('status')).toHaveText('Posted.')
  await bookstore.getByRole('button', { name: 'Close discussions' }).click()
  await expect(studio.row('bookstore')).toBeFocused()
  const saved = JSON.parse((await folder.files())['discussions.json']) as Discussions
  expect(saved.threads.map((thread) => thread.nodeId)).toEqual(['customer', 'bookstore'])
  await view(page, 'System Context')
  await page.locator('button[data-discussion-node="customer"]').click()
  await expect(customer.locator('.discussion-comment')).toContainText('Draft started from the table')
})

test('Viewer table and wiki menus allow discussions without offering model editing', async ({ page, studio }) => {
  await moveToFolder(page)
  await page.locator('.toolbar-mode-btn', { hasText: 'Viewer' }).click()
  await view(page, 'Element Table')
  await studio.row('customer').click({ button: 'right' })
  await expect(page.getByRole('menuitem')).toHaveText(['Discuss'])
  await chooseDiscuss(page)
  const panel = page.getByRole('dialog', { name: 'Customer', exact: true })
  await panel.getByLabel('Comment (Markdown supported)').fill('Reviewing from the table')
  await panel.getByRole('button', { name: 'Post comment' }).click()
  await expect(panel.getByRole('status')).toHaveText('Posted.')
  await panel.getByRole('button', { name: 'Close discussions' }).click()
  await view(page, 'Discussion Wiki')
  await page.locator('.wiki-nav-item[title="Customer"]').click()
  await page.locator('.wiki-title-row').click({ button: 'right' })
  await expect(page.getByRole('menuitem')).toHaveText(['Discuss'])
  await chooseDiscuss(page)
  await expect(panel.locator('.discussion-comment')).toContainText('Reviewing from the table')
  expect((await folder.files())['nodes/customer.md']).toContain('label: "Customer"')
})

test('discussion menus stay unavailable without a folder and keep native menus in text editors', async ({ page, studio }) => {
  await view(page, 'Element Table')
  await studio.row('customer').click({ button: 'right' })
  await expect(page.getByRole('menuitem', { name: 'Discuss', exact: true })).toHaveCount(0)
  await view(page, 'Discussion Wiki')
  await page.locator('.wiki-nav-item[title="Customer"]').click()
  await page.locator('.wiki-title-row').click({ button: 'right' })
  await expect(page.getByRole('menuitem', { name: 'Edit facts' })).toBeVisible()
  await expect(page.getByRole('menuitem', { name: 'Discuss', exact: true })).toHaveCount(0)
  await page.keyboard.press('Escape')
  await moveToFolder(page)
  await view(page, 'Element Table')
  await studio.row('customer').focus()
  await page.keyboard.press('F2')
  const name = studio.row('customer').locator('input')
  await expect(name).toBeFocused()
  await name.click({ button: 'right' })
  await expect(page.getByRole('menuitem', { name: 'Discuss', exact: true })).toHaveCount(0)
  await name.press('Escape')
  await view(page, 'Discussion Wiki')
  await page.locator('.wiki-nav-item[title="Customer"]').click()
  await page.locator('.wiki-title .wiki-heading-text').click()
  const title = page.locator('.wiki-title input')
  await expect(title).toBeVisible()
  await title.click({ button: 'right' })
  await expect(page.getByRole('menuitem', { name: 'Discuss', exact: true })).toHaveCount(0)
  await title.press('Escape')
  await expect(page.locator('.wiki-title')).toHaveText('Customer')
})
